/**
 * 刊会主数据（单一来源）。
 *
 * 用途：选刊手册页面、成果录入的刊会选择器、以及毕业要求等级推导，
 * 都从这一份数据来，避免三处各写一份导致对不上。
 *
 * 数据口径（2026-11 整理）：
 *   - ccf   ：CCF《推荐国际学术会议和期刊目录》，取自 ccf.org.cn 十个领域页面的
 *             全量 644 条逐条比对。**只收计算机方向**，纯电路/器件类期刊会议
 *             （JSSC、TED、ISSCC、CICC 等）本就不在其中，不是"漏收"，因此这类
 *             条目 ccf 留空，不代表水平低。
 *   - cas   ：中科院文献情报中心期刊分区表（升级版）大类分区，按 2025 年 3 月版核对；
 *             会议无分区。影响因子取最新 JIF（2024 JCR）。
 *   - ccfTj ：CCF《计算领域高质量科技期刊分级目录》（2025），只收国内刊。
 *   - csee  ：中国电子学会《高质量科技期刊分级目录》（T1/T2/T3）。注意它
 *             **不是**只收中文刊：T1/T2 里大量是 IEEE Trans.、Nature 子刊
 *             等国际期刊，属于按学科给国内外期刊一起分级。2026 版覆盖
 *             「电子科学与技术 / 信息与通信工程 / 综合」三个子目录，
 *             「计算机技术」仍是 2022 版，引用时要注明版本年份。
 *   查不到的一律留空，页面显示「未知」，不做推测。
 */

export type VenueKind = "期刊" | "会议";

/** 研究方向标签：选刊时先看这个对不对口 */
export const FIELD_TAGS = [
  "EDA/物理设计",
  "体系结构",
  "FPGA/可重构",
  "电路与系统",
  "器件与工艺",
  "测试与可靠性",
  "辐射效应",
  "AI for EDA",
  "综合/交叉",
] as const;
export type FieldTag = (typeof FIELD_TAGS)[number];

export interface VenueRow {
  /** 常用简称（唯一键） */
  abbr: string;
  /** 全称 */
  name: string;
  kind: VenueKind;
  /** 研究方向标签 */
  fields: FieldTag[];
  /** CCF 推荐目录等级；"" = 不在 CCF 目录（不是水平判断） */
  ccf?: "A" | "B" | "C" | "";
  /** CCF 所属领域 */
  ccfDomain?: string;
  /** 中科院大类分区："1区".."4区"；"" = 未知 / 不适用（会议） */
  cas?: string;
  /** 中科院 Top 期刊 */
  casTop?: boolean;
  /** 中国电子学会分级 T1/T2/T3；"" = 不在该目录 */
  csee?: string;
  /** CCF《计算领域高质量科技期刊分级目录》T1/T2/T3（仅国内刊） */
  ccfTj?: string;
  /** 最新影响因子（JCR）；未核实留空 */
  impact?: number;
  /** 期刊 ISSN */
  issn?: string;
  /** 学院原文「一类目录」13 本之一 */
  tier1?: boolean;
  /** 学院原文点名的条目（如集成电路学科单列 NSREC） */
  namedInDoc?: boolean;
  /** 一句话说明：收什么、为什么相关 */
  note: string;
}

