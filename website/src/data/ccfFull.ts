/** 扁平索引：简称 → {等级, 领域中文名, 名称, 出版社} */
export interface CcfIndexed extends CcfVenueRow {
  ccf: "A" | "B" | "C";
  domain: string;
  kind: "期刊" | "会议";
}

export const CCF_INDEX = new Map<string, CcfIndexed>();
for (const d of CCF_DOMAINS) {
  for (const lv of ["a", "b", "c"] as const) {
    for (const v of d[lv]) {
      const key = v.abbr.toUpperCase();
      const prev = CCF_INDEX.get(key);
      const level = lv.toUpperCase() as "A" | "B" | "C";
      // 同一简称跨领域时保留更高等级（A > B > C）
      if (prev && ["A", "B", "C"].indexOf(prev.ccf) <= ["A", "B", "C"].indexOf(level)) continue;
      CCF_INDEX.set(key, { ...v, ccf: level, domain: d.cn, kind: "期刊" });
    }
  }
}
